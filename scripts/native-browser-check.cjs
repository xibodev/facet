// Actual browser controls against an isolated Facet binary and a deterministic
// streaming model endpoint. This verifies integration, not live model quality.
const { chromium } = require('playwright');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const http = require('node:http');
const { spawn, execFileSync } = require('node:child_process');
const assert = require('node:assert/strict');

(async () => {
  await fs.mkdir(path.join(os.tmpdir(),'opencode'),{recursive:true});
  const base = await fs.mkdtemp(path.join(os.tmpdir(), 'opencode', 'facet-native-browser-'));
  const root = path.join(base, 'projects-root'), home = path.join(base, 'home');
  await fs.mkdir(path.join(root,'.facet'), {recursive:true});
  await fs.mkdir(home);
  await fs.writeFile(path.join(root,'.facet','catalog.json'),JSON.stringify({version:'1.0',default_root:path.join(root,'productions'),projects:[]}));
  const modelRequests=[];
  const model = http.createServer(async (req,res) => {
    let raw='';try {for await (const c of req) raw+=c;} catch(error) {if(error.code==='ECONNRESET')return;throw error;}
    const input=JSON.parse(raw);modelRequests.push(input);
    const latest=input.messages.filter(m=>m.role==='user').at(-1)?.content || '';
    if(latest.includes('fail deliberately')) {res.writeHead(503);res.end('Fixture service unavailable');return;}
    const content=latest==='Reply with OK.'?'OK':`Visible reply: ${latest}`;
    const last=input.messages.at(-1);
    const makeCaptions=latest==='Create captions'&&last.role!=='tool';
    const makeVideo=latest==='Trim my footage'&&last.role!=='tool';
    const askApproval=latest==='Request paid operation'&&last.role!=='tool';
    if(!input.stream) {res.setHeader('Content-Type','application/json');res.end(JSON.stringify({choices:[{message:{role:'assistant',content},finish_reason:'stop'}]}));return;}
    res.writeHead(200,{'Content-Type':'text/event-stream'});
    if(latest==='Wait until stopped'){res.write(': waiting\n\n');return;}
    if(askApproval){res.end(`data: ${JSON.stringify({choices:[{index:0,delta:{tool_calls:[{index:0,id:'paid-1',type:'function',function:{name:'openai_image',arguments:JSON.stringify({prompt:'Approval fixture',output_path:'assets/never.png'})}}]},finish_reason:null}]})}\n\ndata: {"choices":[{"index":0,"delta":{},"finish_reason":"tool_calls"}]}\n\ndata: [DONE]\n\n`);return;}
    if(makeVideo){res.end(`data: ${JSON.stringify({choices:[{index:0,delta:{tool_calls:[{index:0,id:'trim-1',type:'function',function:{name:'video_trimmer',arguments:JSON.stringify({operation:'cut',input_path:'assets/source.mp4',output_path:'renders/final.mp4',start_seconds:0,end_seconds:1,codec:'libx264'})}}]},finish_reason:null}]})}\n\ndata: {"choices":[{"index":0,"delta":{},"finish_reason":"tool_calls"}]}\n\ndata: [DONE]\n\n`);return;}
    if(makeCaptions){res.end(`data: ${JSON.stringify({choices:[{index:0,delta:{tool_calls:[{index:0,id:'captions-1',type:'function',function:{name:'subtitle_gen',arguments:JSON.stringify({segments:[{text:'Browser-created captions',start:0,end:2}],format:'srt',output_path:'artifacts/captions.srt'})}}]},finish_reason:null}]})}\n\ndata: {"choices":[{"index":0,"delta":{},"finish_reason":"tool_calls"}]}\n\ndata: [DONE]\n\n`);return;}
    res.write(`data: ${JSON.stringify({choices:[{index:0,delta:{content:'Visible '},finish_reason:null}]})}\n\n`);
    setTimeout(()=>{res.write(`data: ${JSON.stringify({choices:[{index:0,delta:{content:content.slice(8)},finish_reason:null}]})}\n\n`);res.end('data: {"choices":[{"index":0,"delta":{},"finish_reason":"stop"}]}\n\ndata: [DONE]\n\n');},200);
  });
  await new Promise(r=>model.listen(0,'127.0.0.1',r));
  await fs.writeFile(path.join(home,'config.json'),JSON.stringify({version:3,agents:{defaults:{model_name:'fixture/model',max_llm_retries:0}},model_list:['fixture/model','fixture/alternate'].map(model_name=>({model_name,provider:'openai',model:model_name.split('/')[1],api_base:`http://127.0.0.1:${model.address().port}`,enabled:true}))}));
  const app=spawn(path.resolve(process.argv[2]),['ui','--dir',root,'--port','18950','--no-open'],{env:{...process.env,FACET_HOME:home,LOCALAPPDATA:home,HOME:home,USERPROFILE:home},stdio:['ignore','pipe','pipe']});
  let logs='';app.stdout.on('data',d=>logs+=d);app.stderr.on('data',d=>logs+=d);
  let browser;
  const report={base,binary:path.resolve(process.argv[2]),sha256:require('node:crypto').createHash('sha256').update(await fs.readFile(path.resolve(process.argv[2]))).digest('hex'),checks:[],errors:[]};
  try {
    for(let i=0;i<100&&!logs.includes('URL:');i++) await new Promise(r=>setTimeout(r,100));
    const origin=logs.match(/URL: (http:\/\/[^\s]+)/)?.[1];assert.ok(origin,'server did not start');
    browser=await chromium.launch({...(process.env.CI?{}:{channel:'chrome'}),headless:true});
    const page=await browser.newPage({viewport:{width:1440,height:900}});
    page.on('pageerror',e=>report.errors.push(e.message));
    await page.goto(origin);
    assert.equal(await page.title(),'Facet — Video production');
    await page.locator('#btnModelSettings').click();
    await page.locator('#modelSelect').selectOption('fixture/model');
    await page.locator('#btnTestModel').click();
    await page.waitForFunction(()=>document.querySelector('#modelFeedback').textContent.includes('Connected successfully'));
    await page.locator('#btnSaveModel').click();
    await page.waitForFunction(()=>document.querySelector('#modelFeedback').textContent.includes('Saved.'));
    report.checks.push('settings: real selected-model request, saved selection, readable status');
    await page.screenshot({path:path.join(base,'settings.png'),fullPage:true});
    await page.locator('#btnQuickNew').click();
    await page.locator('#newProdName').fill('Native browser production');
    assert.equal(await page.locator('#newProdEngine').isVisible(),false);
    await page.locator('#btnSubmitNewProd').click();
    await page.waitForFunction(()=>document.querySelector('#modalNewProduction').hidden&&!document.querySelector('#promptInput').disabled);
    await page.locator('#promptInput').fill('Remember my blue title');
    await page.locator('#sendButton').click();
    await page.waitForFunction(()=>document.querySelector('#activityList').textContent.includes('Visible reply: Remember my blue title'));
    await page.waitForFunction(()=>!document.querySelector('#promptInput').disabled);
    await page.locator('#promptInput').fill('Continue the project');
    await page.locator('#promptInput').press('Enter');
    await page.waitForFunction(()=>document.querySelector('#activityList').textContent.includes('Visible reply: Continue the project'));
    assert.ok(modelRequests.at(-1).messages.some(m=>m.content?.includes('Remember my blue title')),'follow-up lost conversation context');
    assert.ok(modelRequests.at(-1).messages.some(m=>m.content?.includes('Facet Video Producer')),'missing bundled guidance');
    report.checks.push('new project, visible streamed reply, follow-up context, canonical capability guidance');
    await page.waitForFunction(()=>!document.querySelector('#promptInput').disabled);
    await page.locator('#promptInput').fill('Create captions');await page.locator('#sendButton').click();
    await page.waitForFunction(()=>document.querySelector('#activityList').textContent.includes('Visible reply: Create captions'));
    const captions=await fs.readFile(path.join(root,'productions','native-browser-production','artifacts','captions.srt'),'utf8');
    assert.ok(captions.includes('00:00:00,000 --> 00:00:02,000')&&captions.includes('Browser-created captions'));
    report.checks.push('native subtitle tool created correct timed artifact in selected project');
    const project=path.join(root,'productions','native-browser-production');
    const source=path.join(base,'source.mp4');
    execFileSync('ffmpeg',['-hide_banner','-loglevel','error','-f','lavfi','-i','testsrc2=size=320x180:rate=24','-t','2','-c:v','libx264','-pix_fmt','yuv420p',source]);
    await page.locator('[data-nav=assets]').click();
    await page.getByLabel('Import source media').setInputFiles(source);
    await page.waitForFunction(()=>document.querySelector('#artifactsPanel').textContent.includes('source.mp4'));
    report.checks.push('source media imported using file picker and visible in project assets');
    await page.waitForFunction(()=>!document.querySelector('#promptInput').disabled);
    await page.locator('#promptInput').fill('Trim my footage');await page.locator('#sendButton').click();
    await page.waitForFunction(()=>document.querySelector('#activityList').textContent.includes('Visible reply: Trim my footage'));
    await page.waitForFunction(()=>document.querySelector('#masterVideo').readyState>=2);
    await page.locator('#playButton').click();
    await page.waitForFunction(()=>document.querySelector('#masterVideo').currentTime>0.2);
    await page.locator('[data-nav=assets]').click();
    assert.ok(await page.getByRole('link').filter({hasText:'captions.srt'}).count(),'caption output is not accessible in Assets');
    await page.getByRole('link').filter({hasText:'captions.srt'}).first().click();
    await page.waitForFunction(()=>document.querySelector('#artifactPreviewContent').textContent.includes('Browser-created captions'));
    report.checks.push('artifact view opens actual subtitle content without leaving the application');
    await page.getByRole('button',{name:'Edit document',exact:true}).click();
    await page.getByLabel('Production document content').fill('1\n00:00:00,000 --> 00:00:02,000\nEdited through Facet\n');
    await page.getByRole('button',{name:'Save document',exact:true}).click();
    await page.waitForFunction(()=>document.querySelector('#artifactPreviewContent').textContent.includes('Saved to the project.'));
    assert.ok((await fs.readFile(path.join(project,'artifacts','captions.srt'),'utf8')).includes('Edited through Facet'));
    report.checks.push('artifact document edited and saved through the view');
    const [download]=await Promise.all([page.waitForEvent('download'),page.locator('#videoDownloadLink').click()]);
    const downloaded=path.join(base,'downloaded.mp4');await download.saveAs(downloaded);
    assert.deepEqual(await fs.readFile(downloaded),await fs.readFile(path.join(project,'renders','final.mp4')));
    const probe=JSON.parse(execFileSync('ffprobe',['-v','error','-show_format','-show_streams','-of','json',path.join(project,'renders','final.mp4')],{encoding:'utf8'}));
    assert.ok(Number(probe.format.duration)>0&&probe.streams[0].width===320);
    execFileSync('ffmpeg',['-hide_banner','-loglevel','error','-i',path.join(project,'renders','final.mp4'),'-frames:v','1',path.join(base,'rendered-frame.png')]);
    report.checks.push('native video trim, actual decoded output, browser playback and matching download');
    await page.locator('[data-nav=review]').click();
    for(const [id,value]of Object.entries({reviewWidth:'320',reviewHeight:'180',reviewFPS:'24',reviewDuration:'1'}))await page.locator('#'+id).fill(value);
    await page.locator('#runReview').click();await page.waitForFunction(()=>document.querySelector('#reviewFeedback').textContent.startsWith('Technical review:'));
    await page.locator('#confirmReview').check();await page.locator('#acceptOutput').click();
    await page.waitForFunction(()=>document.querySelector('#reviewFeedback').textContent.includes('exact file digest'));
    const acceptance=JSON.parse(await fs.readFile(path.join(project,'review','acceptance.json'),'utf8'));assert.equal(acceptance.human_approved,true);assert.equal(acceptance.sha256.length,64);
    report.checks.push('technical review and separate human acceptance through Review view');
    await page.reload();
    await page.waitForFunction(()=>document.querySelector('#activityList').textContent.includes('Remember my blue title'));
    report.checks.push('reload restores actual conversation text');
    await page.waitForFunction(()=>!document.querySelector('#promptInput').disabled);
    await page.locator('#promptInput').fill('fail deliberately');await page.locator('#sendButton').click();
    await page.waitForFunction(()=>document.querySelector('#activityList').textContent.includes('Fixture service unavailable')||document.querySelector('#liveText').textContent.includes('503'));
    await page.waitForFunction(()=>!document.querySelector('#promptInput').disabled);
    await page.locator('#promptInput').fill('Recovered');await page.locator('#sendButton').click();
    await page.waitForFunction(()=>document.querySelector('#activityList').textContent.includes('Visible reply: Recovered'));
    report.checks.push('provider error visible, composer recovers, next turn succeeds');
    await page.waitForFunction(()=>!document.querySelector('#promptInput').disabled);
    await page.locator('#promptInput').fill('Request paid operation');await page.locator('#sendButton').click();
    await page.getByRole('button',{name:'Decline',exact:true}).click();
    await page.waitForFunction(()=>!document.querySelector('#promptInput').disabled);
    assert.equal(await fs.stat(path.join(project,'assets','never.png')).then(()=>true,()=>false),false);
    report.checks.push('kernel approval displayed, user decline prevents paid execution');
    await page.locator('#promptInput').fill('Wait until stopped');await page.locator('#sendButton').click();
    await page.waitForFunction(()=>document.querySelector('#connectionText').textContent.includes('Working'));
    await page.locator('#sessionControl').click();
    await page.waitForFunction(()=>!document.querySelector('#promptInput').disabled);
    await page.locator('#promptInput').fill('After stopping');await page.locator('#sendButton').click();
    await page.waitForFunction(()=>document.querySelector('#activityList').textContent.includes('Visible reply: After stopping'));
    report.checks.push('cancel active model request and continue afterward');
    await page.waitForFunction(()=>!document.querySelector('#promptInput').disabled);
    await page.locator('#btnModelSettings').click();await page.locator('#modelSelect').selectOption('fixture/alternate');
    const savedResponse=page.waitForResponse(r=>new URL(r.url()).pathname==='/api/models'&&r.request().method()==='POST');
    await page.locator('#btnSaveModel').click();
    const saved=await savedResponse;report.modelSave={request:saved.request().postData(),response:await saved.json()};
    await page.waitForFunction(()=>!document.querySelector('#btnSaveModel').disabled);
    await page.locator('[data-nav=produce]').click();
    await page.locator('#promptInput').fill('Changed model');await page.locator('#sendButton').click();
    await page.waitForFunction(()=>document.querySelector('#activityList').textContent.includes('Visible reply: Changed model'));
    const changedRequest=modelRequests.findLast(r=>r.messages.at(-1)?.content==='Changed model');
    assert.equal(changedRequest.model,'alternate');
    assert.ok(changedRequest.messages.some(m=>m.content?.includes('Remember my blue title')));
    report.checks.push('model change uses selected model while retaining project history');
    await page.screenshot({path:path.join(base,'conversation.png'),fullPage:true});
    await page.locator('[data-nav=projects]').click();
    assert.equal(await page.locator('#inspector').isVisible(),false);
    assert.equal(await page.locator('#composer').isVisible(),false);
    report.checks.push('project library shows projects without unrelated conversation controls');
    await page.setViewportSize({width:390,height:844});
    await page.locator('[data-nav=settings]').click();
    await page.screenshot({path:path.join(base,'mobile.png'),fullPage:true});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    assert.deepEqual(report.errors,[]);
    report.status='passed';
  } catch(error) {report.status='failed';report.error=error.stack;process.exitCode=1;if(browser)await browser.contexts()[0].pages()[0].screenshot({path:path.join(base,'failure.png'),fullPage:true});}
  finally {if(browser)await browser.close();app.kill();model.closeAllConnections();model.close();await fs.writeFile(path.join(base,'report.json'),JSON.stringify(report,null,2));await fs.writeFile(path.join(base,'server.log'),logs);console.log(JSON.stringify(report,null,2));}
})();
